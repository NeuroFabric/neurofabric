function thousands(value: number): string {
  return value.toLocaleString("en-US");
}

/**
 * THE FACTOR, DEFINED PRECISELY, because a number without a definition is an
 * oracle.
 *
 * It is the ratio of the worst observed value to the 3x-IQR outer fence that
 * value cleared. The fence is used rather than a standard deviation because one
 * absurd value inflates the very sigma it has to clear -- a column of 199 values
 * near zero and one at 9,999,999.99 has sigma around 700,000, so the point reads
 * as "about 13 sigma" and is detectable only because it is so absurd. Tukey
 * fences are built from quartiles, and one value cannot move a quartile.
 *
 * The fence is already published in the report as `fenceExtremeUpper`, so this
 * claim is checkable against a number the engine prints rather than against a
 * formula buried here.
 */
function factorOf(value: number, fence: number | null): number | null {
  if (fence === null || fence === 0) return null;
  const ratio = Math.abs(value / fence);
  if (!Number.isFinite(ratio)) return null;
  return ratio;
}

/**
 * THE XSS-SAFE EMBED. The load-bearing function in this file.
 *
 * `JSON.stringify` alone is NOT sufficient inside a `<script>` element, because
 * it does not escape `<`. A string containing `</script>` terminates the block
 * early, and everything after it is parsed as script by the browser. This is the
 * single most common way server-rendered JSON becomes an XSS hole, and the
 * values here are the contents of a file the user handed us.
 *
 * So `<`, `>` and `&` become their JSON unicode escapes, which are ordinary
 * characters to a JS parser and meaningless to an HTML tokenizer. U+2028 and
 * U+2029 are escaped too: they are valid in JSON and illegal unescaped in a
 * JavaScript string literal, so a column name containing one would be a parse
 * error that breaks the whole dashboard. Every one of these is reversible, so
 * the data round-trips to the exact original string.
 */
export function embedJson(value: unknown): string {
  return JSON.stringify(value)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

/**
 * Turn one column's health into zero or more findings, worst first.
 *
 * Severity is derived from the ENGINE'S OWN THRESHOLDS rather than invented here:
 * an anomaly past the 3x outer fence is `critical`, a marginal one (past 1.5x)
 * is `warning`, and structural damage -- type mismatches and empty cells -- is
 * also `warning` because it is a defect in the producer rather than in the data.
 * A second threshold of our own would be a third number nobody can reconcile
 * with the report.
 */
function anomaliesFrom(health: ColumnHealth, stat: NumericColumnStat | undefined): Anomaly[] {
  const found: Anomaly[] = [];
  if (health.outliers > 0 && health.worstValue !== null) {
    found.push({
      column: health.column,
      severity: "critical",
      kind: "extreme value",
      detail: `${thousands(Math.abs(health.worstValue))} against a fence of ${thousands(Math.round(health.fence ?? 0))}`,
      factor: factorOf(health.worstValue, health.fence),
    });
  } else if (stat?.outliers !== undefined && stat.outliers > 0 && stat.outlierMax !== null) {
    found.push({
      column: health.column,
      severity: "warning",
      kind: "marginal value",
      detail: `${thousands(stat.outliers)} value(s) past the 1.5x fence, worst ${thousands(stat.outlierMax)}`,
      factor: factorOf(stat.outlierMax, stat.fenceExtremeUpper ?? null),
    });
  }
  if (health.dirty > 0) {
    found.push({
      column: health.column,
      severity: "warning",
      kind: "type mismatch",
      detail: `${health.dirty} cell(s) hold something that is not a number${health.examples.length > 0 ? `, e.g. ${health.examples.join(", ")}` : ""}`,
      factor: null,
    });
  }
  if (health.empty > 0) {
    found.push({
      column: health.column,
      severity: "info",
      kind: "missing values",
      detail: `${health.empty} empty cell(s)`,
      factor: null,
    });
  }
  return found;
}

/** Build the payload the app renders. Pure, so it can be tested without a browser. */
export function buildDashboardData(analysis: BottleneckAnalysis, options: DashboardOptions = {}): DashboardData {
  const byName = new Map(analysis.numerical.columns.map((c) => [c.column, c]));
  const anomalies: Anomaly[] = [];
  // Health first, so a column with both an extreme value and a type mismatch
  // contributes both and the filter can show either.
  for (const health of analysis.health.columns) {
    anomalies.push(...anomaliesFrom(health, byName.get(health.column)));
  }
  return {
    title: options.title ?? "Data review",
    headline: options.headline ?? `${analysis.totalRows} row(s) read.`,
    totalRows: analysis.totalRows,
    columns: analysis.numerical.columns.map((c) => ({
      name: c.column,
      mean: c.mean,
      min: c.min,
      max: c.max,
      measured: c.measured,
      dirty: c.dirty,
      empty: c.empty,
    })),
    anomalies,
    ranking: analysis.categories.slice(0, MAX_DEPTH).map((c) => ({ key: c.key, count: c.count })),
    maxDepth: MAX_DEPTH,
    defaultDepth: DEFAULT_DEPTH,
    source: options.live?.path ?? null,
    timeline: analysis.hourly.hours.map((h) => ({
      hour: h.key,
      count: h.count,
      share: h.share,
      multiple: h.multiple,
      spike: h.isSpike,
      rule: h.rule,
    })),
    // Seeded from the analysis itself. A role the engine filled while profiling
    // IS a mapping it holds, whether or not a person confirmed it, and the chat
    // has to start from what the engine believes or the first correction looks
    // like it is starting from nothing.
    learned: options.learned ?? rolesToMap(analysis),
  };
}

/**
 * The role -> column map the profiler already settled on.
 *
 * Read off the schema the analysis was built with rather than re-derived, so
 * the chat shows the engine's actual belief. A panel that disagreed with the
 * report beside it would be worse than no panel.
 */
function rolesToMap(analysis: BottleneckAnalysis): Record<string, string> {
  const schema = (analysis as { schema?: { roles?: Readonly<Record<string, string>> } }).schema;
  const out: Record<string, string> = {};
  for (const [role, column] of Object.entries(schema?.roles ?? {})) {
    if (typeof column === "string" && column !== "") out[role] = column;
  }
  return out;
}


