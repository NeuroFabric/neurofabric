/** A finding the filter can act on. Severity is a CLOSED set, not an observation. */
export type Severity = "critical" | "warning" | "info";

export interface Anomaly {
  readonly column: string;
  readonly severity: Severity;
  /** What is wrong, in a phrase. Never a number without a unit. */
  readonly kind: string;
  /** The magnitude, pre-formatted, so the app does not have to guess at units. */
  readonly detail: string;
  /**
   * How many times past the 3x-IQR fence the worst value sits, when there is a
   * fence to divide by. Null when the finding is not a magnitude one, because
   * the filter shows a "factor" column and a blank there means "not applicable"
   * rather than "one".
   */
  readonly factor: number | null;
}

/** One hour of the day, as the engine measured it. */
export interface TimelinePoint {
  /** ISO hour key, "2026-09-30T13". Sorts chronologically as a string. */
  readonly hour: string;
  readonly count: number;
  /** Fraction of all readable rows, so a quiet hour is not shown as a crisis. */
  readonly share: number;
  /** count / meanPerHour, or null when there is no mean to divide by. */
  readonly multiple: number | null;
  /** The engine's own verdict against its own mean. */
  readonly spike: boolean;
  /** Why it was flagged, in a phrase. Null when it was not. */
  readonly rule: string | null;
}

