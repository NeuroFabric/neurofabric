/**
 * THE INTERACTIVE DASHBOARD. One string, no build step, no install.
 *
 * WHY THIS IS A STRING AND NOT A COMPONENT TREE. The product's claim is that a
 * fresh clone runs. A React app assembled from source files would need a
 * toolchain, a lockfile and a build, and every one of those is a way for "it
 * worked on my machine" to become "it did not work for the user". So this emits
 * a complete document, and the document is the deliverable. It is the same
 * decision the inline-SVG chart generator made one session earlier, for the
 * same reason.
 *
 * === THE ONE PLACE THIS PRODUCT RUNS THIRD-PARTY SCRIPT, AND WHY IT IS ISOLATED
 *
 * React is loaded from a CDN rather than vendored, and that is a real trade and
 * not a free choice. The cost is that the page executes code this repository
 * does not control, on a machine that has just been trusted to read the user's
 * files. The mitigation is ISOLATION rather than hope:
 *
 *   - This is a SEPARATE ARTIFACT from the kernel's own page. The wedge at
 *     platform/web/page.ts keeps `default-src 'none'` and loads nothing remote;
 *     the test suite pins that difference so nobody widens the kernel's page to
 *     match this one in the name of consistency.
 *   - The application code below is generated by us and is small enough to read.
 *   - The CDN versions are PINNED, and asserted by test. An unpinned reference
 *     means a report about a production incident can change because somebody
 *     else published a package.
 *   - The app reads only the JSON block beside it. It has no network calls, so
 *     there is nothing for injected script to exfiltrate even if it ran.
 *
 * What this does NOT give us is integrity of the CDN itself. Pinning the version
 * stops silent drift, not a compromised publisher. The honest options are to
 * vendor the two files at build time or to pin by subresource-integrity hash,
 * and both need the hashes to be generated and checked by the build, which this
 * repository does not have. That is recorded as standing debt rather than
 * described as solved.
 *
 * THE PAYLOAD IS UNTRUSTED, AND THAT IS THE OTHER HALF OF THE RISK. The embedded
 * JSON holds column names and cell values taken from a file the user dropped, so
 * a column called `</script><script>...` is not a hypothetical -- ingesting
 * arbitrary files is the product. `embedJson` is therefore the load-bearing
 * function in this file, and it escapes the three characters that can end a
 * script block or break a JS string literal, at the JSON level so the data still
 * parses back to the exact original string.
 */

