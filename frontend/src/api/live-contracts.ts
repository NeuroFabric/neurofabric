import { isRecord, type ShapeResult } from "./contracts";

/**
 * THE LIVE VERDICT CONTRACT, MIRRORED.
 *
 * These mirror `platform/conductor/live-anomaly.ts` and
 * `platform/egress/webhook-dispatcher.ts`.
 *
 * === WHAT THIS FILE REFUSES TO DO ===
 *
 * The brief asked the telemetry view to "prove the 257k event/sec throughput is
 * happening". It cannot, and nothing here pretends otherwise.
 *
 * There is no throughput metric anywhere in the backend. `LiveVerdict` carries
 * `records` -- how many records a snapshot saw -- and that is a count, not a
 * rate. A rate needs two instants and a numerator, and no endpoint reports
 * either. So no component in this workspace displays "257,000 events/sec",
 * because a number rendered as a measurement and derived from nothing is the
 * single most expensive thing a dashboard can do: it is unfalsifiable, it will
 * survive every refactor, and someone will eventually quote it.
 *
 * What IS offered instead:
 *   - a real verdict rendered faithfully when one arrives, and
 *   - a SYNTHETIC sample, generated by `simulateVerdict`, for exercising the
 *     view when nothing is live -- carrying `synthetic: true`, which every
 *     renderer is required to display. A simulated figure that cannot be
 *     mistaken for a measurement is a fixture. One that can is a lie.
 *
 * If a real throughput endpoint is added later, this file gains a validator and
 * a fetcher, and no component changes: they already take the verdict as a prop
 * and already have somewhere to put its provenance.
 */

export interface LiveColumnVerdict {
  readonly column: string;
  readonly partition: string;
  readonly measured: number;
  readonly min: number | null;
  readonly max: number | null;
  readonly q1: number | null;
  readonly q3: number | null;
  /** True when the quantiles were SAMPLED rather than exact. Never render a sampled fence as exact. */
  readonly quantilesSampled: boolean;
  readonly fenceLower: number | null;
  readonly fenceUpper: number | null;
  readonly extremeLower: number | null;
  readonly extremeUpper: number | null;
  readonly extremeMultiple: number | null;
  readonly breached: boolean;
  readonly partitions: number;
  readonly breachedEverywhere: boolean;
}

export interface LiveVerdict {
  readonly at: string;
  readonly records: number;
  readonly open: boolean;
  readonly columns: readonly LiveColumnVerdict[];
  readonly breachedColumns: number;
  readonly busiestHour: { readonly hour: string; readonly count: number } | null;
  readonly topKeys: readonly { readonly key: string; readonly count: number }[];
  /**
   * PROVENANCE. `false` means a real measurement from a real snapshot.
   * `true` means generated by `simulateVerdict` and must be labelled in the UI.
   */
  readonly synthetic: boolean;
}

/**
 * A MEASURED RATE, mirroring `platform/omniroute/throughput-meter.ts`.
 *
 * The window travels with the rate because a rate without it is not a
 * measurement: sampled over 40ms and over 10s are both "events/sec" and can
 * differ by orders of magnitude around a burst. A dashboard that prints the rate
 * and hides the window is choosing to look authoritative while being
 * uninterpretable.
 */
export interface ThroughputReading {
  readonly records: number;
  readonly delta: number;
  readonly windowMs: number;
  readonly eventsPerSecond: number;
}

/** The `GET /api/portal/live` body. Nulls are explicit and each one means something. */
export interface LiveSnapshot {
  readonly at: string;
  readonly provider: string;
  readonly enabled: boolean;
  /** Null before the first event arrives. Distinct from "connected but idle". */
  readonly verdict: LiveVerdict | null;
  /** Null until two observations exist. See `ThroughputMeter`, which is why. */
  readonly throughput: ThroughputReading | null;
}

/**
 * VALIDATE A LIVE SNAPSHOT.
 *
 * The throughput half is validated as strictly as the verdict, because a dashboard
 * rendering a NaN or an Infinity rate because a field went missing is the exact
 * untrustworthiness this whole layer was added to prevent.
 */
export function validateLiveSnapshot(input: unknown): ShapeResult<LiveSnapshot> {
  if (!isRecord(input)) {
    return { ok: false, issues: [{ path: "$", reason: "a live snapshot must be an object" }] };
  }
  if (typeof input.at !== "string") {
    return { ok: false, issues: [{ path: "$.at", reason: "at is required" }] };
  }
  if (typeof input.provider !== "string" || input.provider.trim() === "") {
    return { ok: false, issues: [{ path: "$.provider", reason: "provider is required" }] };
  }
  if (typeof input.enabled !== "boolean") {
    return { ok: false, issues: [{ path: "$.enabled", reason: "enabled must be a boolean" }] };
  }

  let verdict: LiveVerdict | null = null;
  if (input.verdict !== null && input.verdict !== undefined) {
    const inner = validateLiveVerdict(input.verdict);
    if (!inner.ok) {
      return { ok: false, issues: inner.issues.map((issue) => ({ ...issue, path: `$.verdict${issue.path}` })) };
    }
    verdict = inner.value;
  }

  let throughput: ThroughputReading | null = null;
  const raw = input.throughput;
  if (raw !== null && raw !== undefined) {
    if (!isRecord(raw)) {
      return { ok: false, issues: [{ path: "$.throughput", reason: "throughput must be an object or null" }] };
    }
    for (const key of ["records", "delta", "windowMs", "eventsPerSecond"] as const) {
      const value = raw[key];
      if (typeof value !== "number" || !Number.isFinite(value)) {
        return { ok: false, issues: [{ path: `$.throughput.${key}`, reason: "must be a finite number" }] };
      }
    }
    // A non-positive window means the rate was computed over no interval at all --
    // a divide by zero that reached the wire. Refusing it here is what stops an
    // `Infinity events/sec` appearing on a live dashboard.
    if ((raw.windowMs as number) <= 0) {
      return { ok: false, issues: [{ path: "$.throughput.windowMs", reason: "a rate must publish a positive window" }] };
    }
    throughput = {
      records: raw.records as number,
      delta: raw.delta as number,
      windowMs: raw.windowMs as number,
      eventsPerSecond: raw.eventsPerSecond as number,
    };
  }

  return { ok: true, value: { at: input.at, provider: input.provider, enabled: input.enabled, verdict, throughput } };
}

export interface AlertColumn {
  readonly column: string;
  readonly partitions: number;
  readonly max: number | null;
  readonly fenceUpper: number | null;
  readonly multiple: number | null;
  readonly breachedEverywhere: boolean;
}

export interface AlertPayload {
  readonly id: string;
  readonly title: string;
  readonly body: string;
  readonly severity: "info" | "warning" | "critical";
  readonly source: string;
  readonly at: string;
  readonly summary: {
    readonly records: number;
    readonly open: boolean;
    readonly breachedColumns: number;
    readonly partitions: number;
  };
  readonly columns: readonly AlertColumn[];
}

export function validateLiveVerdict(input: unknown): ShapeResult<LiveVerdict> {
  const issues: { path: string; reason: string }[] = [];
  if (!isRecord(input)) {
    return { ok: false, issues: [{ path: "$", reason: "a live verdict must be an object" }] };
  }
  if (typeof input.at !== "string") issues.push({ path: "$.at", reason: "at is required" });
  if (typeof input.records !== "number" || !Number.isFinite(input.records)) {
    issues.push({ path: "$.records", reason: "records must be a number" });
  }
  if (typeof input.open !== "boolean") issues.push({ path: "$.open", reason: "open must be a boolean" });
  if (typeof input.breachedColumns !== "number") {
    issues.push({ path: "$.breachedColumns", reason: "breachedColumns must be a number" });
  }
  if (!Array.isArray(input.columns)) issues.push({ path: "$.columns", reason: "columns must be an array" });
  if (!Array.isArray(input.topKeys)) issues.push({ path: "$.topKeys", reason: "topKeys must be an array" });
  // `synthetic` must be EXPLICIT. A payload arriving from the wire without it is
  // refused rather than defaulted to false: defaulting would mean a source that
  // forgot the field would be rendered as a real measurement, which is exactly
  // the confusion this whole module exists to prevent.
  if (typeof input.synthetic !== "boolean") {
    issues.push({ path: "$.synthetic", reason: "synthetic must be stated explicitly: a verdict may not be assumed real" });
  }

  if (issues.length > 0) return { ok: false, issues };
  return { ok: true, value: input as unknown as LiveVerdict };
}

/**
 * A SYNTHETIC verdict, for exercising the view when nothing is live.
 *
 * Deterministic for a given `seed`, so a test can assert on it and a developer
 * can reproduce a screenshot. Determinism matters: a generator that differs on
 * every call makes every visual test flaky and every bug report unreproducible.
 */
export function simulateVerdict(seed: number, records: number): LiveVerdict {
  // A tiny LCG. Not for anything cryptographic; only so the shape is stable.
  let state = (seed * 2654435761) % 2147483647;
  const next = (): number => {
    state = (state * 48271) % 2147483647;
    return state / 2147483647;
  };

  const names = ["latency_ms", "elapsed_time", "queue_depth", "error_rate"];
  const partitions = ["part-0", "part-1", "part-2"];
  const columns: LiveColumnVerdict[] = names.map((name, i) => {
    const base = 100 + Math.floor(next() * 900);
    const q1 = base;
    const q3 = base + 50 + Math.floor(next() * 100);
    const breached = next() > 0.6;
    const max = breached ? q3 * (1.5 + next()) : q3;
    return {
      column: name,
      partition: partitions[i % partitions.length] ?? "part-0",
      measured: 1000 + Math.floor(next() * 9000),
      min: q1,
      max,
      q1,
      q3,
      quantilesSampled: true,
      fenceLower: q1,
      fenceUpper: q3,
      extremeLower: q1,
      extremeUpper: q3,
      extremeMultiple: breached ? Number((1 + next() * 3).toFixed(2)) : null,
      breached,
      partitions: partitions.length,
      breachedEverywhere: breached && next() > 0.5,
    };
  });

  const breachedCount = columns.filter((column) => column.breached).length;
  return {
    at: "1970-01-01T00:00:00.000Z",
    records,
    open: breachedCount > 0,
    columns,
    breachedColumns: breachedCount,
    busiestHour: { hour: "1970-01-01T09", count: Math.floor(records * 0.25) },
    topKeys: Array.from({ length: 5 }, (_, i) => ({ key: `key-${i}`, count: Math.floor(records / (5 + i)) })),
    synthetic: true,
  };
}